"""CP5 extension: are there more alert hours around certain events? (DECISIONS D-20)

Events (data/events/events.csv) were listed and committed before this analysis.
Statistic for a set of events: mean over events of the mean alert hours per day in the
window [e - 1, e + 3]. Null distribution: local placebo permutation - every event date is
replaced by a random date within +-30 days (at least 5 days away, so the windows do not
overlap) and the statistic is recomputed, 10 000 times. Local placebos keep the slow
changes of the alert level (2022 vs 2024 vs autumn 2026) out of the comparison.
p (one-sided) = share of placebo statistics >= the observed one.
"""
import numpy as np
import pandas as pd

from .config import REPORTS, RESULTS, ROOT

WINDOW = (-1, 3)
PLACEBO_RANGE, PLACEBO_MIN_GAP = 30, 5
N_PERM = 10_000
CITIES = ("kyiv", "kharkiv", "dnipro")


def window_mean(y, day):
    """Mean hours over [day-1, day+3]; missing days are skipped. NaN if no observed day."""
    idx = [day + pd.Timedelta(days=k) for k in range(WINDOW[0], WINDOW[1] + 1)]
    v = y.reindex(idx)
    return v.mean() if v.notna().any() else np.nan


def analyse(daily, events, city, seed=0):
    y = daily[daily.city == city].set_index(pd.to_datetime(daily[daily.city == city].date)).hours
    lo, hi = y.index.min() - pd.Timedelta(days=WINDOW[0]), y.index.max() - pd.Timedelta(days=WINDOW[1])
    rng = np.random.default_rng(seed)
    offsets = np.array([o for o in range(-PLACEBO_RANGE, PLACEBO_RANGE + 1) if abs(o) >= PLACEBO_MIN_GAP])
    rows = []
    for cat, ev in list(events.groupby("category")) + [("all", events)]:
        days = [d for d in pd.to_datetime(ev.date) if lo <= d <= hi]
        obs_each = np.array([window_mean(y, d) for d in days])
        keep = ~np.isnan(obs_each)
        days, obs_each = [d for d, k in zip(days, keep) if k], obs_each[keep]
        observed = obs_each.mean()
        # placebo table: for every event, the window mean at every allowed offset
        table = np.array([[window_mean(y, d + pd.Timedelta(days=int(o))) for o in offsets] for d in days])
        picks = rng.integers(0, len(offsets), size=(N_PERM, len(days)))
        perm = np.nanmean(table[np.arange(len(days)), picks], axis=1)
        local = np.nanmean(table, axis=1)                      # each event's local average
        rows.append({"city": city, "category": cat, "n_events": len(days),
                     "hours_event_window": observed, "hours_local_placebo": float(np.mean(perm)),
                     "excess_h": observed - float(np.mean(perm)),
                     "excess_ci95_lo": observed - np.quantile(perm, 0.975),
                     "excess_ci95_hi": observed - np.quantile(perm, 0.025),
                     "share_events_above_local": float((obs_each > local).mean()),
                     "p_more": float((perm >= observed).mean()),
                     "p_less": float((perm <= observed).mean())})
    return pd.DataFrame(rows)


def main():
    from .build import load_processed
    _, daily = load_processed()
    events = pd.read_csv(ROOT / "data" / "events" / "events.csv")
    res = pd.concat([analyse(daily, events, c) for c in CITIES], ignore_index=True)
    RESULTS.mkdir(exist_ok=True)
    res.round(4).to_csv(RESULTS / "events_effects.csv", index=False)
    L = ["# CP5 extension: alert hours around events (generated by `airalerts/events.py`)", "",
         f"Events: `data/events/events.csv` ({len(events)} dated events, committed before the analysis).",
         f"Window [{WINDOW[0]}, +{WINDOW[1]}] days around each event; local placebo permutation: each date",
         f"moved by a random {PLACEBO_MIN_GAP}..{PLACEBO_RANGE} days (either side), {N_PERM} times.",
         "excess_h = mean hours/day in event windows minus the placebo mean; CI from the placebo distribution;",
         "p_more = P(placebo >= observed), p_less = P(placebo <= observed). No correction for the",
         f"{len(res)} tests is applied in the table - with 15 tests one p < 0.05 is expected by chance.", "",
         res.round(3).to_markdown(index=False), ""]
    (REPORTS / "events.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    return res


if __name__ == "__main__":
    print(main().round(3).to_string(index=False))
