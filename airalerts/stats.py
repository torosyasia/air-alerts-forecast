"""Headline facts per city from the cleaned data (after all fixes in DECISIONS D-04..D-08).

Episodes are merged alerts (overlapping records of oblast/raion/city counted once; a pause
of <= 60 s, e.g. a level change, does not start a new episode). Days of the channel outage
(D-06a) are excluded, and so is every episode or quiet period that touches them.
"""
import numpy as np
import pandas as pd

from . import intervals as iv
from .build import load_processed
from .config import EPISODE_GAP_S, REPORTS, RESULTS, TZ

CITIES = ("kyiv", "kharkiv", "dnipro", "lviv")
NAME = {"kyiv": "Київ", "kharkiv": "Харків", "dnipro": "Дніпро", "lviv": "Львів"}


def city_facts(records, daily, city):
    d = daily[daily.city == city]
    obs = d[~d.missing]
    miss = set(d.date[d.missing])
    first, last = d.date.min(), d.date.max()
    lo = pd.Timestamp(first).tz_localize(TZ).tz_convert("UTC")
    hi = (pd.Timestamp(last) + pd.Timedelta(days=1)).tz_localize(TZ).tz_convert("UTC")
    r = records[records.city == city]
    s, e = iv.merge(r.started_at, r.finished_at, gap_s=EPISODE_GAP_S)
    ep = pd.DataFrame({"start": pd.to_datetime(s, utc=True), "end": pd.to_datetime(e, utc=True)})
    ep = ep[(ep.start >= lo) & (ep.end <= hi)]
    days_of = lambda a, b: set(pd.date_range(a.tz_convert(TZ).date(), b.tz_convert(TZ).date()).date)
    ep = ep[[not (days_of(a, b) & miss) for a, b in zip(ep.start, ep.end)]]
    ep["h"] = (ep.end - ep.start).dt.total_seconds() / 3600
    longest = ep.loc[ep.h.idxmax()]
    q = pd.DataFrame({"start": ep.end.to_numpy()[:-1], "end": ep.start.to_numpy()[1:]})
    q["start"], q["end"] = pd.to_datetime(q.start, utc=True), pd.to_datetime(q.end, utc=True)
    q = q[[not (days_of(a, b) & miss) for a, b in zip(q.start, q.end)]]
    q["h"] = (q.end - q.start).dt.total_seconds() / 3600
    quiet = q.loc[q.h.idxmax()]
    rec_day = obs.loc[obs.hours.idxmax()]
    rec_ep = obs.loc[obs.n_episodes.idxmax()]
    obs = obs.assign(year=pd.to_datetime(obs.date).dt.year, month=pd.to_datetime(obs.date).dt.to_period("M"))
    by_year = obs.groupby("year").hours.sum() / obs.groupby("year").day_len_h.sum()  # unrounded
    month = obs.groupby("month").hours.mean()
    fmt = lambda t: t.tz_convert(TZ).strftime("%d.%m.%Y %H:%M")
    return {
        "city": city, "period": f"{first}..{last}", "days_observed": len(obs), "days_missing": len(miss),
        "episodes_total": int(obs.n_episodes.sum()), "hours_total": round(obs.hours.sum(), 0),
        "share_time_under_alert": obs.hours.sum() / obs.day_len_h.sum(),
        **{f"share_{y}": v for y, v in by_year.items()},
        "share_days_without_alert": (obs.hours == 0).mean(),
        "median_episode_min": round(ep.h.median() * 60, 0),
        "longest_episode_h": round(longest.h, 1), "longest_episode": f"{fmt(longest.start)} → {fmt(longest.end)}",
        "longest_quiet_days": round(quiet.h / 24, 1), "longest_quiet": f"{fmt(quiet.start)} → {fmt(quiet.end)}",
        "record_day_hours": round(rec_day.hours, 1), "record_day": str(rec_day.date),
        "record_day_episodes": int(rec_ep.n_episodes), "record_episodes_day": str(rec_ep.date),
        "busiest_month": str(month.idxmax()), "busiest_month_h_per_day": round(month.max(), 1),
    }


def main():
    records, daily = load_processed()
    t = pd.DataFrame([city_facts(records, daily, c) for c in CITIES])
    RESULTS.mkdir(exist_ok=True)
    t.round(4).to_csv(RESULTS / "city_facts.csv", index=False)
    (REPORTS / "facts.md").write_text("# Facts per city (generated by `airalerts/stats.py`)\n\n"
                                      + t.set_index("city").T.to_markdown() + "\n", encoding="utf-8")
    return t


def markdown(t):
    t = t.set_index("city")
    years = [c for c in t.columns if c.startswith("share_20")]
    row = lambda label, f: "| " + label + " | " + " | ".join(f(t.loc[c]) for c in CITIES) + " |"
    L = ["| | " + " | ".join(NAME[c] for c in CITIES) + " |", "|---|" + "---|" * len(CITIES),
         row("Тривог (епізодів) з 16.03.2022", lambda r: f"{int(r.episodes_total):,}".replace(",", " ")),
         row("Годин під тривогою", lambda r: f"{int(r.hours_total):,}".replace(",", " ")),
         row("Частка часу під тривогою, усього", lambda r: f"{r.share_time_under_alert:.0%}")]
    for y in years:
        row_label = f"… у {y[-4:]}" + (" (з 16.03)" if y.endswith("2022") else "") + \
                    (" (до останньої доби)" if y == years[-1] else "")
        L.append(row(row_label, lambda r, y=y: f"{r[y]:.0%}"))
    L += [row("Днів без жодної тривоги", lambda r: f"{r.share_days_without_alert:.0%}" if r.share_days_without_alert >= 0.005 else "<1%"),
          row("Медіанна тривалість тривоги", lambda r: f"{r.median_episode_min:.0f} хв"),
          row("Найдовша тривога", lambda r: f"{r.longest_episode_h:.1f} год ({r.longest_episode.split(' ')[0]})"),
          row("Найдовша тиша", lambda r: f"{r.longest_quiet_days:.1f} доби (з {r.longest_quiet.split(' ')[0]})"),
          row("Рекордна доба за годинами", lambda r: f"{r.record_day_hours:.1f} год ({pd.Timestamp(r.record_day):%d.%m.%Y})"),
          row("Рекордна доба за кількістю тривог", lambda r: f"{r.record_day_episodes} ({pd.Timestamp(r.record_episodes_day):%d.%m.%Y})"),
          row("Найнапруженіший місяць", lambda r: f"{r.busiest_month} ({r.busiest_month_h_per_day:.1f} год/добу)")]
    return "\n".join(L)


if __name__ == "__main__":
    t = main()
    print(t.T.to_string())
    print(markdown(t))
